let currentLang = "es";

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (STRINGS[lang]) {
    currentLang = lang;
  }
}

export function t(key) {
  return STRINGS[currentLang][key] || STRINGS.en[key] || key;
}

export function polName(pol) {
  return t(`pol_${pol}`);
}

